"""Read, validate, and write the sources used by player-packet generation."""

from __future__ import annotations

import json
import re
from collections import Counter
from dataclasses import dataclass
from pathlib import Path
from typing import Mapping


GENERATED_BY = "tools/generate_player_packets.py"
DEFAULT_LANGUAGE = "en"
LANGUAGE_DIRECTORY = Path("languages")
PLAYER_PACKET_TEMPLATE = Path("layout/player_packet.template.tex")
PLAYER_PACKET_ENTITY_TEMPLATE = Path("layout/player_packet_entity.template.tex")
TEMPLATE_TOKEN_RE = re.compile(r"@@([A-Z][A-Z0-9_]*)@@")
GENERATED_MARKERS = (
    "% Generated by tools/generate_player_packets.py",
    "% Generated by compile.py",
    "%% Generated by tools/generate_player_packets.py",
    "# Generated by tools/generate_player_packets.py",
    "// Generated by tools/generate_player_packets.py",
    "<!-- Generated by tools/generate_player_packets.py",
)
INPUT_RE = re.compile(r"\\(?:MMInput|input)\s*\{([^{}]+)\}")
CHARACTER_RE = re.compile(r"\\Character\s*\{([^{}]+)\}")
CONFIGURED_NAME_RE = re.compile(r"\\MMCharacterName\s*\{([^{}]+)\}\s*\{([^{}]+)\}")
LANGUAGE_RE = re.compile(r"[A-Za-z0-9]+(?:-[A-Za-z0-9]+)*")
RELATIONSHIP_MAP_HEADING_RE = re.compile(r"\\MMRelationshipMapHeading\b")
HOST_GUIDANCE_HEADING_RE = re.compile(r"^\\MMHostGuidanceHeading\b", flags=re.MULTILINE)
CHARACTER_IMAGE_SUFFIXES = (".png", ".jpg", ".jpeg", ".pdf")
SPACE_PHOTO_DIRECTORY = Path("content/assets/space")
SPACE_PHOTO_SUFFIXES = (".png", ".jpg", ".jpeg", ".pdf")


@dataclass(frozen=True)
class Sheet:
    """An entity declaration discovered in one of the component indexes."""

    entity_id: str
    title: str
    source: Path
    latex: str


class SourceError(RuntimeError):
    """Raised when the repository's declared source structure is invalid."""


def validate_language(language: str) -> str:
    """Validate a BCP 47-style locale identifier used in repository paths."""

    if not LANGUAGE_RE.fullmatch(language):
        raise SourceError(
            f"Invalid language '{language}'. Use a locale such as '{DEFAULT_LANGUAGE}' or 'pt-PT'."
        )
    return language


def source_path(root: Path, relative_path: Path | str, language: str = DEFAULT_LANGUAGE) -> Path:
    """Return a localized source file when it overlays the default source.

    Every localized file mirrors its repository-relative default path below
    ``languages/<locale>/``. Missing files deliberately fall back to the
    default source, which lets a translation be completed incrementally.
    """

    language = validate_language(language)
    root = root.resolve()
    relative = Path(relative_path)
    if relative.is_absolute():
        raise SourceError(f"Localized source paths must be repository-relative: {relative_path}")
    base = (root / relative).resolve()
    try:
        base.relative_to(root)
    except ValueError as error:
        raise SourceError(f"Localized source path is outside the repository: {relative_path}") from error

    localized = (root / LANGUAGE_DIRECTORY / language / relative).resolve()
    try:
        localized.relative_to(root / LANGUAGE_DIRECTORY / language)
    except ValueError as error:
        raise SourceError(f"Localized source path is outside its language pack: {relative_path}") from error
    return localized if localized.is_file() else base


def source_directory(root: Path, relative_path: Path | str, language: str = DEFAULT_LANGUAGE) -> Path:
    """Return a localized directory when an entire asset directory is overlaid."""

    language = validate_language(language)
    root = root.resolve()
    relative = Path(relative_path)
    if relative.is_absolute() or ".." in relative.parts:
        raise SourceError(f"Localized source directories must be repository-relative: {relative_path}")
    localized = root / LANGUAGE_DIRECTORY / language / relative
    return localized if localized.is_dir() else root / relative


def language_file(root: Path, language: str, name: str) -> Path:
    """Return a required, pack-owned file such as ``strings.tex``."""

    language = validate_language(language)
    path = root.resolve() / LANGUAGE_DIRECTORY / language / name
    if not path.is_file():
        raise SourceError(f"Language pack '{language}' is missing required file: {path}")
    return path


def verify_language_pack(root: Path, language: str) -> list[Path]:
    """Validate the files explicitly required by a complete language pack.

    A pack's ``manifest.txt`` contains one repository-relative source path per
    line. This is intentionally opt-in: normal localized builds may use the
    default-language fallback while a translation is in progress.
    """

    manifest = language_file(root, language, "manifest.txt")
    required: list[Path] = []
    seen: set[Path] = set()
    for line_number, raw_line in enumerate(read_text(manifest).splitlines(), start=1):
        line = raw_line.strip()
        if not line or line.startswith("#"):
            continue
        path = Path(line)
        if path.is_absolute() or ".." in path.parts:
            raise SourceError(f"Invalid path in {manifest}:{line_number}: {line}")
        if path in seen:
            raise SourceError(f"Duplicate path in {manifest}:{line_number}: {line}")
        seen.add(path)
        required.append(path)

    unknown = [path for path in required if path != Path("strings.tex") and not (root / path).is_file()]
    if unknown:
        rendered = ", ".join(path.as_posix() for path in unknown)
        raise SourceError(f"Language pack '{language}' manifest names no default source: {rendered}")

    missing = [path for path in required if not (root / LANGUAGE_DIRECTORY / language / path).is_file()]
    if missing:
        rendered = ", ".join(path.as_posix() for path in missing)
        raise SourceError(f"Language pack '{language}' is incomplete; missing: {rendered}")
    return required


def read_text(path: Path) -> str:
    try:
        return path.read_text(encoding="utf-8")
    except FileNotFoundError as error:
        raise SourceError(f"Required source file does not exist: {path}") from error


def render_template(path: Path, values: Mapping[str, str]) -> str:
    """Render a repository template containing ``@@UPPERCASE_TOKENS@@``."""

    template = read_text(path)
    tokens = {match.group(1) for match in TEMPLATE_TOKEN_RE.finditer(template)}
    missing = tokens - values.keys()
    unused = values.keys() - tokens
    if missing:
        raise SourceError(f"Template {path} is missing values for: {', '.join(sorted(missing))}")
    if unused:
        raise SourceError(f"Template {path} does not contain values for: {', '.join(sorted(unused))}")
    return TEMPLATE_TOKEN_RE.sub(lambda match: values[match.group(1)], template)


def tex_path(path: Path) -> str:
    """Return a path that is readable by TeX on every supported platform."""

    return path.as_posix()


def consume_braced(text: str, start: int) -> tuple[str, int]:
    """Read one balanced LaTeX braced argument starting at ``start``."""

    if start >= len(text) or text[start] != "{":
        raise SourceError(f"Expected '{{' near character {start}")
    depth = 0
    position = start
    while position < len(text):
        char = text[position]
        escaped = position > 0 and text[position - 1] == "\\"
        if char == "{" and not escaped:
            depth += 1
        elif char == "}" and not escaped:
            depth -= 1
            if depth == 0:
                return text[start + 1 : position], position + 1
        position += 1
    raise SourceError(f"Unclosed '{{' near character {start}")


def extract_macro_calls(text: str, macro: str, argument_count: int = 3) -> list[tuple[list[str], str]]:
    """Extract full calls and their balanced arguments for a simple LaTeX macro."""

    token = f"\\{macro}"
    results: list[tuple[list[str], str]] = []
    search_from = 0
    while True:
        start = text.find(token, search_from)
        if start == -1:
            break
        token_end = start + len(token)
        if token_end < len(text) and text[token_end].isalpha():
            search_from = token_end
            continue
        position = token_end
        arguments: list[str] = []
        try:
            for _ in range(argument_count):
                while position < len(text) and text[position].isspace():
                    position += 1
                argument, position = consume_braced(text, position)
                arguments.append(argument)
        except SourceError:
            search_from = token_end
            continue
        results.append((arguments, text[start:position]))
        search_from = position
    return results


def resolve_input(root: Path, including_file: Path, target: str, language: str = DEFAULT_LANGUAGE) -> Path:
    """Resolve an input exactly as ``\\MMInput`` does for localized sources."""

    relative_target = Path(target)
    if relative_target.suffix == "":
        relative_target = relative_target.with_suffix(".tex")
    if relative_target.is_absolute():
        raise SourceError(f"Input outside the repository is not supported: {target}")

    candidates = [(root / relative_target).resolve(), (including_file.parent / relative_target).resolve()]
    for candidate in candidates:
        try:
            relative_candidate = candidate.relative_to(root)
        except ValueError:
            continue
        resolved = source_path(root, relative_candidate, language)
        if resolved.is_file():
            return resolved
    raise SourceError(f"Could not resolve \\input{{{target}}} from {including_file}")


def files_from_index(root: Path, index_file: Path, language: str = DEFAULT_LANGUAGE) -> list[Path]:
    """Return an index and the local files it transitively includes, in order."""

    seen: set[Path] = set()
    files: list[Path] = []

    def visit(path: Path) -> None:
        path = path.resolve()
        if path in seen:
            return
        seen.add(path)
        files.append(path)
        for target in INPUT_RE.findall(read_text(path)):
            visit(resolve_input(root, path, target, language))

    visit(index_file.resolve())
    return files


def parse_sheets(
    root: Path,
    index_relative_path: Path | str,
    macro: str,
    argument_count: int = 3,
    language: str = DEFAULT_LANGUAGE,
) -> list[Sheet]:
    """Parse entity sheets whose first argument is an identifier and second is a title."""

    sheets: list[Sheet] = []
    index_file = source_path(root, index_relative_path, language)
    for source in files_from_index(root, index_file, language):
        for arguments, latex in extract_macro_calls(read_text(source), macro, argument_count):
            title = arguments[0].strip() if argument_count == 2 else arguments[1].strip()
            sheets.append(Sheet(arguments[0].strip(), title, source, latex.strip()))
    duplicate_ids = [entity_id for entity_id, count in Counter(sheet.entity_id for sheet in sheets).items() if count > 1]
    if duplicate_ids:
        raise SourceError(f"Duplicate {macro} identifiers: {', '.join(sorted(duplicate_ids))}")
    return sheets


def parse_configured_names(config_path: Path) -> dict[str, str]:
    return {
        identifier.strip(): name.strip()
        for identifier, name in CONFIGURED_NAME_RE.findall(read_text(config_path))
    }


def character_short_description(character: Sheet) -> str:
    """Return a character's optional ``\\shortdescription`` body."""

    descriptions = extract_macro_calls(character.latex, "shortdescription", argument_count=1)
    if len(descriptions) > 1:
        raise SourceError(f"Character '{character.entity_id}' declares more than one \\shortdescription")
    return descriptions[0][0][0].strip() if descriptions else ""


def player_safe_character_sheet(character: Sheet) -> str:
    """Return a character sheet with its trailing ``\\GMNotes`` section omitted.

    ``\\GMNotes`` is deliberately authored as the final section of a character
    sheet. The main document retains them, while this copy is used only in the
    player's individual packet.
    """

    sheets = extract_macro_calls(character.latex, "CharacterSheet")
    if len(sheets) != 1:
        raise SourceError(f"Character '{character.entity_id}' must declare exactly one \\CharacterSheet")
    arguments, _ = sheets[0]
    body = arguments[2]
    semantic_notes = extract_macro_calls(body, "GMNotes", argument_count=1)
    if len(semantic_notes) > 1:
        raise SourceError(f"Character '{character.entity_id}' declares more than one \\GMNotes section")
    if semantic_notes:
        marker = semantic_notes[0][1]
        position = body.find(marker)
        if body[position + len(marker) :].strip():
            raise SourceError(f"Character '{character.entity_id}' must put \\GMNotes at the end of its sheet")
        player_body = body[:position].rstrip()
    else:
        return character.latex
    return f"\\CharacterSheet{{{arguments[0]}}}{{{arguments[1]}}}{{\n{player_body}\n}}"


def character_image_path(root: Path, character_id: str, language: str = DEFAULT_LANGUAGE) -> str:
    """Return a TeX-readable character image path, falling back to the placeholder."""

    image_directory = source_directory(root, Path("config/character_imgs"), language)
    matches = sorted(
        candidate
        for candidate in image_directory.glob(f"{character_id}.*")
        if candidate.is_file() and candidate.stem == character_id and candidate.suffix.lower() in CHARACTER_IMAGE_SUFFIXES
    )
    image = matches[0] if matches else image_directory / "placeholder.png"
    if not image.is_file():
        raise SourceError(
            f"No image exists for character '{character_id}' and the placeholder is missing: {image_directory / 'placeholder.png'}"
        )
    return tex_path(image.relative_to(root))


def space_photo_paths(root: Path, language: str = DEFAULT_LANGUAGE) -> list[str]:
    """Return the supported space-photo files in a stable display order."""

    image_directory = source_directory(root, SPACE_PHOTO_DIRECTORY, language)
    if not image_directory.is_dir():
        return []
    images = sorted(
        (
            candidate
            for candidate in image_directory.iterdir()
            if candidate.is_file() and candidate.suffix.lower() in SPACE_PHOTO_SUFFIXES
        ),
        key=lambda candidate: candidate.name.casefold(),
    )
    return [tex_path(image.relative_to(root)) for image in images]


def parse_mystery_dependencies(mysteries_path: Path, mysteries: list[Sheet]) -> list[tuple[str, str]]:
    """Read ``\\MysteryDependency{solve-first}{solve-next}`` declarations."""

    dependencies = [
        (arguments[0].strip(), arguments[1].strip())
        for arguments, _ in extract_macro_calls(read_text(mysteries_path), "MysteryDependency", 2)
    ]
    known_labels = {mystery.entity_id for mystery in mysteries}
    unknown_labels = sorted({label for dependency in dependencies for label in dependency if label not in known_labels})
    if unknown_labels:
        raise SourceError("Mystery dependencies refer to undeclared labels: " + ", ".join(unknown_labels))
    return dependencies


def mysteries_in_dependency_order(mysteries: list[Sheet], dependencies: list[tuple[str, str]]) -> list[Sheet]:
    """Return a stable topological order, preserving source order where possible."""

    source_order = [mystery.entity_id for mystery in mysteries]
    successors: dict[str, set[str]] = {label: set() for label in source_order}
    incoming: dict[str, int] = {label: 0 for label in source_order}
    for before, after in dependencies:
        if after not in successors[before]:
            successors[before].add(after)
            incoming[after] += 1

    ordered_labels: list[str] = []
    ready = [label for label in source_order if incoming[label] == 0]
    while ready:
        label = ready.pop(0)
        ordered_labels.append(label)
        for successor in source_order:
            if successor in successors[label]:
                incoming[successor] -= 1
                if incoming[successor] == 0:
                    ready.append(successor)

    if len(ordered_labels) != len(source_order):
        raise SourceError("Mystery dependencies contain a cycle")
    by_label = {mystery.entity_id: mystery for mystery in mysteries}
    return [by_label[label] for label in ordered_labels]


def find_relationship_items(relationship_map_path: Path) -> list[str]:
    source = read_text(relationship_map_path)
    heading = RELATIONSHIP_MAP_HEADING_RE.search(source)

    if not heading:
        raise SourceError(f"{relationship_map_path} has no 'Atomic facts' subsection")

    following_subsection = re.search(r"\\subsection\s*\{", source[heading.end() :])
    section = source[heading.end() : heading.end() + following_subsection.start()] if following_subsection else source[heading.end() :]
    match = re.search(r"\\begin\s*\{itemize\}(.*?)\\end\s*\{itemize\}", section, flags=re.DOTALL)
    if not match:
        raise SourceError("The Atomic facts subsection must contain an itemize environment")
    items = re.split(r"\\item(?:\s*\[[^\]]*\])?", match.group(1))
    return [re.sub(r"\s+", " ", item).strip() for item in items[1:] if item.strip()]


def latex_to_plain(text: str) -> str:
    """Provide a readable graph label without attempting full TeX rendering."""

    previous = None
    result = text
    while previous != result:
        previous = result
        result = re.sub(r"\\[A-Za-z@]+\s*\{([^{}]*)\}", r"\1", result)
    result = re.sub(r"\\[A-Za-z@]+", "", result)
    result = result.replace("{", "").replace("}", "")
    return re.sub(r"\s+", " ", result).strip()


def owned_write(path: Path, content: str) -> None:
    """Write one generated file without replacing a non-generated user file."""

    if path.exists():
        existing = read_text(path)
        if existing == content:
            return
        is_owned_json = False
        if path.suffix == ".json":
            try:
                is_owned_json = json.loads(existing).get("generated_by") == GENERATED_BY
            except json.JSONDecodeError:
                pass
        if not existing.startswith(GENERATED_MARKERS) and not is_owned_json:
            raise SourceError(f"Refusing to replace non-generated file: {path}")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8", newline="\n")


def owned_unlink(path: Path) -> None:
    """Remove a generated file without ever deleting an authored file."""

    if not path.exists():
        return
    existing = read_text(path)
    if not existing.startswith(GENERATED_MARKERS):
        raise SourceError(f"Refusing to remove non-generated file: {path}")
    path.unlink()


def player_safe_rules(root: Path, language: str = DEFAULT_LANGUAGE) -> str:
    """Copy the dedicated player rules while keeping authoring guidance GM-only."""

    source = read_text(source_path(root, "content/general_rules.tex", language))
    gm_rules = read_text(source_path(root, "content/gm_rules.tex", language))
    host_guidance = HOST_GUIDANCE_HEADING_RE

    if host_guidance.search(source):
        raise SourceError(
            "Host guidance belongs in content/gm_rules.tex, not content/general_rules.tex"
        )
    if not host_guidance.search(gm_rules):
        raise SourceError("content/gm_rules.tex must mark host guidance with \\MMHostGuidanceHeading")
    return source.rstrip()
